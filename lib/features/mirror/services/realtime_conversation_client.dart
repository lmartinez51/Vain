/// @file realtime_conversation_client.dart
/// @brief Abstract definition for real-time conversation clients interfacing with AI models.
/// @author Lorenzo Martínez
/// @date 2026-03-30
/// @version 1.0.0
library;

import 'package:flutter/foundation.dart';

/// @brief Abstract base class defining the contract for real-time AI conversation services.
abstract class RealtimeConversationClient extends Listenable {
  /// @brief Opens the real-time session, performs handshakes, and applies initial configurations.
  /// @param instructions Optional context or personality instructions for the AI.
  /// @param userPhotoPath Optional path to the user's photo for context.
  /// @param isProfileComplete Indicates if the user profile is fully hydrated.
  /// @return A completed [Future] when the session is successfully started.
  Future<void> startSession({
    String? instructions,
    String? userPhotoPath,
    bool isProfileComplete = true,
  });

  /// @brief Sends a chunk of PCM audio data to the open session.
  /// @param pcm The 16-bit mono audio buffer (16kHz or 24kHz depending on backend).
  void sendAudioChunk(Uint8List pcm);

  /// @brief Safely closes the real-time session and terminates connections.
  /// @return A completed [Future] when the session is closed.
  Future<void> stopSession();

  /// @brief Releases resources and listeners associated with the client.
  void dispose();

  /// @brief Retrieves the URL of the last generated image during the session, if any.
  String? get lastGeneratedImageUrl;

  // --------------------------------------------------
  // Callbacks (asignados por el controller)
  // --------------------------------------------------

  /// @brief Callback providing PCM audio generated by the AI assistant.
  void Function(Uint8List pcm)? onAssistantAudio;

  /// @brief Callback triggered when the AI assistant begins speaking.
  void Function()? onAssistantSpeakingStart;

  /// @brief Callback triggered when the server generates a response container.
  void Function()? onResponseCreated;

  /// @brief Callback triggered when the AI assistant finishes speaking.
  void Function()? onAssistantSpeakingEnd;

  /// @brief Callback triggered when the Voice Activity Detection (VAD) detects user speech.
  void Function()? onUserSpeechStarted;

  /// @brief Callback triggered when VAD detects the user has stopped speaking.
  void Function()? onUserSpeechStopped;

  /// @brief Callback triggered when the server successfully commits the user's speech buffer.
  void Function()? onUserSpeechCommitted;

  /// @brief Callback providing the real-time transcription of the user's speech.
  void Function(String transcript)? onUserTranscript;

  /// @brief Callback providing the real-time transcription of the AI assistant's speech.
  void Function(String transcript)? onAssistantTranscript;

  /// @brief Callback providing a data update for the user's profile parsed from the conversation.
  void Function(Map<String, dynamic> data)? onUserProfileUpdate;

  /// @brief Callback triggered when DALL-E image generation is initiated.
  void Function()? onImageGenerationStarted;

  /// @brief Callback triggered when DALL-E image generation completes successfully.
  void Function()? onImageGenerationCompleted;

  /// @brief Callback providing fatal session errors.
  void Function(Object error)? onError;
}
